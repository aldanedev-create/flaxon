def _one_line(text: str) -> str:
    return " ".join(text.split())


def _summary(target: Any) -> str:
    doc = inspect.getdoc(target) or ""
    return _one_line(doc.split("\n\n", 1)[0].strip())


def _signature(target: Any) -> str:
    try:
        signature = inspect.signature(target, eval_str=True)
    except (TypeError, ValueError, NameError):
        return ""
    text = _one_line(str(signature).replace("'", "")).replace("(self, ", "(").replace("(self)", "()")
    # Sentinel defaults carry a per-process memory address; normalise it so
    # generated docs are deterministic across runs.
    return re.sub(r"<object object at 0x[0-9a-fA-F]+>", "<sentinel>", text)


# -- verification of pitfalls against live code -----------------------------


def check_route_syntax() -> bool:
    """Return True when the routing module exposes the int converter."""
    from flaxon.routing import CONVERTERS  # noqa: PLC0415 - lazy import keeps checks isolated

    return "int" in CONVERTERS


def check_openapi_flag() -> bool:
    """Return True when Flaxon.__init__ accepts an openapi flag."""
    from flaxon import Flaxon  # noqa: PLC0415 - lazy import keeps checks isolated

    return "openapi" in inspect.signature(Flaxon).parameters  # type: ignore[arg-type]


def check_standard_extra() -> bool:
    """Return True when the standard extra includes uvicorn and websockets."""
    import tomllib  # noqa: PLC0415 - lazy import keeps checks isolated

    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    extra = data["project"]["optional-dependencies"]["standard"]
    return any("uvicorn" in item for item in extra) and any("websockets" in item for item in extra)


def check_validation_shape() -> bool:
    """Return True when the validation error code constant matches the docs."""
    from flaxon.constants import VALIDATION_ERROR_CODE  # noqa: PLC0415 - lazy import keeps checks isolated

    return VALIDATION_ERROR_CODE == "FX-VAL-001"


def check_test_client_kwargs() -> bool:
    """Return True when the async client documents query and json_data."""
    from flaxon.testing import AsyncTestClient  # noqa: PLC0415 - lazy import keeps checks isolated

    source = inspect.getsource(AsyncTestClient.request)
    return "json_data" in source and "query" in source


def check_template_names() -> bool:
    """Return True when the CLI template names match the docs."""
    from flaxon.cli.project_templates import template_names  # noqa: PLC0415 - lazy import keeps checks isolated

    return set(template_names()) == {"basic", "api", "api-db", "web", "fullstack"}


def check_admin_registration() -> bool:
    """Return True when the admin registration surface matches the docs."""
    from flaxon.admin import AdminDashboard  # noqa: PLC0415 - lazy import keeps checks isolated
    from flaxon.admin.resources import Resource  # noqa: PLC0415 - lazy import keeps checks isolated

    return hasattr(AdminDashboard, "register") and hasattr(Resource, "fields")


def check_ws_origin() -> bool:
    """Return True when the WebSocket origin close code matches the docs."""
    from flaxon.websocket.origin import POLICY_VIOLATION  # noqa: PLC0415 - lazy import keeps checks isolated

    return POLICY_VIOLATION == 1008


CHECKS = {
    "route_syntax": check_route_syntax,
    "openapi_flag": check_openapi_flag,
    "standard_extra": check_standard_extra,
    "validation_shape": check_validation_shape,
    "test_client_kwargs": check_test_client_kwargs,
    "template_names": check_template_names,
    "admin_registration": check_admin_registration,
    "ws_origin": check_ws_origin,
}


def verify_pitfalls() -> list[str]:
    """Return the topic names whose documented facts no longer hold."""
    return [row["topic"] for row in PITFALLS if not CHECKS[row["check"]]()]


# -- renderers ---------------------------------------------------------------


def _doc_text(doc: str, generated: dict[str, str]) -> str:
    """Read a doc from disk, or from the freshly generated map."""
    key = f"docs/{doc}"
    if key in generated:
        return generated[key]
    return (ROOT / "docs" / doc).read_text(encoding="utf-8")


def render_llms_txt(generated: dict[str, str] | None = None) -> str:
    """Return the llms.txt index with verified key facts."""
    generated = generated or {}
    lines = [
        "# Flaxon",
        "",
        f"> Flaxon {__version__}: Python APIs, Teloce interfaces and a production admin in one framework.",
        "> Full documentation: llms-full.txt (version-stamped concatenation of the core pages below).",
        "",
    ]
    for doc in CORE_DOCS + GENERATED_DOCS:
        text = _doc_text(doc, generated)
        title = next((line[2:] for line in text.splitlines() if line.startswith("# ")), doc)
        summary = next((line for line in text.splitlines() if line.strip() and not line.startswith("#")), "")
        lines.append(f"- [{title.strip()}]({doc}): {_one_line(summary)[:160]}")
    lines += [
        "",
        "## Key facts (verified against code)",
        "",
        "- Route parameters use `<int:id>` converters, never `{id}` or `{id:int}`.",
        "- Enable `/docs` with `Flaxon('app', openapi=True)`; a plain app has no docs route.",
        "- Install `flaxon[standard]` so WebSockets work (plain uvicorn returns 404).",
        "- Minimum runtime dependencies: `orjson`, `PyJWT`, `argon2-cffi`.",
        "- Validation errors are HTTP 422 with `error.code == 'FX-VAL-001'` and `error.fields`.",
        "- Test clients send JSON bodies with `json_data=`, query strings with `query=`.",
        "- `flaxon new NAME --template` accepts `basic`, `api`, `api-db`, `web`, `fullstack`.",
        "- A bad WebSocket `Origin` is rejected before accept with close code `1008` (HTTP 403).",
        "- A model becomes a full admin with a `Resource` subclass then `dashboard.register(...)`.",
        "- A Teloce admin field is `TeloceField(name, Component(...), fallback=...)` "
        "with a real HTML control.",
        "",
        "## Recipes",
        "",
    ]
    for recipe in sorted((ROOT / "docs" / "ai" / "recipes").glob("*.md")):
        text = recipe.read_text(encoding="utf-8")
        title = next((line[2:] for line in text.splitlines() if line.startswith("# ")), recipe.stem)
        lines.append(f"- [{title.strip()}](docs/ai/recipes/{recipe.name})")
    return "\n".join(lines).rstrip() + "\n"


def render_llms_full(generated: dict[str, str] | None = None) -> str:
    """Return the version-stamped llms-full.txt bundle."""
    generated = generated or {}
    parts = [
        f"# Flaxon documentation bundle — version {__version__}",
        "",
        "Generated by scripts/generate_ai_docs.py. Do not edit by hand.",
        "",
    ]
    for doc in CORE_DOCS + GENERATED_DOCS:
        parts.append(f"\n\n---\n\n# Source: docs/{doc}\n")
        parts.append(_doc_text(doc, generated).strip())
    for recipe in sorted((ROOT / "docs" / "ai" / "recipes").glob("*.md")):
        parts.append(f"\n\n---\n\n# Source: docs/ai/recipes/{recipe.name}\n")
        parts.append(recipe.read_text(encoding="utf-8").strip())
    return "\n".join(parts).rstrip() + "\n"


